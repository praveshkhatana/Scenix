#!/usr/bin/env node
'use strict';
/*
 * Generate the portable token boundary for native targets that do not share Android Views.
 *
 * Android remains the reference implementation, but its JSON tokens must not be manually copied
 * into a future SwiftUI or WinUI renderer.  This tool creates deterministic, source-controlled
 * inputs for those renderers and `check` makes stale generated output a review failure.
 *
 *   node design-system/tools/platform-tokens.mjs write
 *   node design-system/tools/platform-tokens.mjs check
 *   node design-system/tools/platform-tokens.mjs list
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, '..');
const TOKEN_ROOT = path.join(ROOT, 'tokens');
const OUTPUT_ROOT = path.join(ROOT, 'generated');
const SWIFT_FILE = path.join(OUTPUT_ROOT, 'ios', 'ScenixDesignTokens.swift');
const XAML_FILE = path.join(OUTPUT_ROOT, 'windows', 'ScenixTokens.xaml');

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function catalog() {
  const index = readJson(path.join(TOKEN_ROOT, 'index.json'));
  if (!Array.isArray(index.themes) || !index.themes.length) {
    throw new Error('design-system/tokens/index.json must declare at least one theme');
  }
  return index.themes.map((entry) => {
    if (!entry?.id || !entry?.name || !entry?.file) {
      throw new Error('every token index entry needs id, name and file');
    }
    const theme = readJson(path.join(TOKEN_ROOT, 'themes', entry.file));
    if (theme.id !== entry.id || theme.name !== entry.name || !theme.tokens) {
      throw new Error(`token catalog drift for ${entry.id}`);
    }
    return theme;
  });
}

function flatTokens(theme) {
  const out = [];
  for (const group of Object.keys(theme.tokens).sort()) {
    const values = theme.tokens[group];
    if (!values || typeof values !== 'object' || Array.isArray(values)) {
      throw new Error(`${theme.id}.${group} must be a token object`);
    }
    for (const key of Object.keys(values).sort()) {
      const value = values[key];
      if (!isPortableValue(value)) {
        throw new Error(`${theme.id}.${group}.${key} is not a portable token value`);
      }
      out.push({ key: `${group}.${key}`, value });
    }
  }
  return out;
}

function isPortableValue(value) {
  if (['string', 'number', 'boolean'].includes(typeof value)) return true;
  return Array.isArray(value) && value.every((item) => ['string', 'number', 'boolean'].includes(typeof item));
}

function swiftString(value) {
  // JSON's \uXXXX escapes are not Swift escapes. Keep the generator safe for a future
  // display string with a control character while preserving normal Unicode scalars.
  const escaped = [...value].map((character) => {
    if (character === '\\') return '\\\\';
    if (character === '"') return '\\"';
    const scalar = character.codePointAt(0);
    if (scalar <= 0x1f || scalar === 0x7f) return `\\u{${scalar.toString(16)}}`;
    return character;
  }).join('');
  return `"${escaped}"`;
}

function swiftValue(value) {
  if (typeof value === 'string') return `.string(${swiftString(value)})`;
  if (typeof value === 'number') return `.number(${String(value)})`;
  if (Array.isArray(value)) return `.array([${value.map(swiftValue).join(', ')}])`;
  return `.boolean(${value ? 'true' : 'false'})`;
}

function swift(themes) {
  const lines = [
    '// Generated by design-system/tools/platform-tokens.mjs. Do not edit by hand.',
    '// Source: design-system/tokens/*.json',
    '',
    'public indirect enum ScenixTokenValue: Equatable {',
    '    case string(String)',
    '    case number(Double)',
    '    case boolean(Bool)',
    '    case array([ScenixTokenValue])',
    '}',
    '',
    'public struct ScenixThemeTokens: Equatable {',
    '    public let id: String',
    '    public let name: String',
    '    public let values: [String: ScenixTokenValue]',
    '',
    '    public init(id: String, name: String, values: [String: ScenixTokenValue]) {',
    '        self.id = id',
    '        self.name = name',
    '        self.values = values',
    '    }',
    '}',
    '',
    'public enum ScenixThemeCatalog {',
    '    public static let all: [ScenixThemeTokens] = [',
  ];
  themes.forEach((theme, themeIndex) => {
    lines.push(`        ScenixThemeTokens(id: ${swiftString(theme.id)}, name: ${swiftString(theme.name)}, values: [`);
    const tokens = flatTokens(theme);
    tokens.forEach((token, index) => {
      lines.push(`            ${swiftString(token.key)}: ${swiftValue(token.value)}${index === tokens.length - 1 ? '' : ','}`);
    });
    lines.push(`        ])${themeIndex === themes.length - 1 ? '' : ','}`);
  });
  lines.push(
    '    ]',
    '',
    '    public static func theme(id: String) -> ScenixThemeTokens? {',
    '        all.first { $0.id == id }',
    '    }',
    '}',
    '',
  );
  return lines.join('\n');
}

function xml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&apos;');
}

function xamlColor(value) {
  if (typeof value !== 'string') return null;
  const hex = value.trim();
  if (/^#[0-9a-f]{6}$/i.test(hex)) return `#FF${hex.slice(1).toUpperCase()}`;
  if (/^#[0-9a-f]{8}$/i.test(hex)) return `#${hex.slice(1).toUpperCase()}`;
  return null;
}

function xaml(themes) {
  const lines = [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
    '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
    '  <!-- Generated by design-system/tools/platform-tokens.mjs. Do not edit by hand. -->',
  ];
  for (const theme of themes) {
    lines.push(`  <!-- ${xml(theme.name)} (${xml(theme.id)}) -->`);
    for (const token of flatTokens(theme)) {
      const key = `${theme.id}.${token.key}`;
      const color = xamlColor(token.value);
      if (color) lines.push(`  <Color x:Key="${xml(key)}">${color}</Color>`);
      else if (typeof token.value === 'number') lines.push(`  <x:Double x:Key="${xml(key)}">${token.value}</x:Double>`);
      else if (typeof token.value === 'boolean') lines.push(`  <x:Boolean x:Key="${xml(key)}">${token.value}</x:Boolean>`);
      else {
        const literal = Array.isArray(token.value) ? JSON.stringify(token.value) : token.value;
        lines.push(`  <x:String x:Key="${xml(key)}">${xml(literal)}</x:String>`);
      }
    }
  }
  lines.push('</ResourceDictionary>', '');
  return lines.join('\n');
}

function expected() {
  const themes = catalog();
  return new Map([
    [SWIFT_FILE, swift(themes)],
    [XAML_FILE, xaml(themes)],
  ]);
}

function write() {
  for (const [file, contents] of expected()) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, contents);
    console.log(`wrote ${path.relative(process.cwd(), file)}`);
  }
}

function check() {
  let stale = 0;
  for (const [file, contents] of expected()) {
    const actual = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (actual !== contents) {
      console.error(`STALE   ${path.relative(process.cwd(), file)} — run platform-tokens.mjs write`);
      stale++;
    } else {
      console.log(`ok      ${path.relative(process.cwd(), file)}`);
    }
  }
  if (stale) process.exit(1);
  console.log('platform token exports are current');
}

function list() {
  for (const theme of catalog()) {
    console.log(`${theme.id.padEnd(18)} ${theme.name.padEnd(14)} ${flatTokens(theme).length} scalar tokens`);
  }
}

const command = process.argv[2] || 'list';
if (command === 'write') write();
else if (command === 'check') check();
else if (command === 'list') list();
else {
  console.error('usage: platform-tokens.mjs write|check|list');
  process.exit(2);
}
